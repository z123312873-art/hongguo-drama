const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const signer = require('../src/native/player-signing');
const url = 'https://example.com/play?aid=8662&device_id=1234567890123456&version_name=7.3.5.32&_rticket=1794387600123';
const options = { random: Buffer.from('01020304', 'hex'), nonce: 0xffffffff };
const body = Buffer.from('{"items":["11"]}');
const a = signer.headers(url, body, options);
assert.equal(a['x-khronos'], '1794387600');
assert.equal(a['x-ss-req-ticket'], '1794387600123');
assert.equal(a['x-ss-stub'], crypto.createHash('md5').update(body).digest('hex'));
assert.deepEqual(signer.headers(url, body, options), a);
assert.equal(Buffer.from(a['x-argus'], 'base64').subarray(0, 2).toString('hex'), 'f281');
assert.ok(Buffer.from(a['x-argus'], 'base64').length > 100);
assert.equal(Buffer.from(a['x-ladon'], 'base64').subarray(0, 4).toString('hex'), '01020304');
assert.notEqual(signer.headers(url, Buffer.from('{}'), options)['x-argus'], a['x-argus']);
assert.notEqual(signer.headers(url.replace('aid=8662', 'aid=1967'), body, options)['x-argus'], a['x-argus']);
assert.notEqual(signer.headers(url.replace('version_name=7.3.5.32', 'version_name=7.4.3.32'), body, options)['x-argus'], a['x-argus']);
assert.notEqual(signer.headers(url, body)['x-argus'], signer.headers(url, body)['x-argus']);
assert.equal(signer.headers(url, null, options)['x-ss-stub'], undefined);
for (const name of ['x-gorgon', 'x-medusa', 'x-helios', 'Cookie', 'X-Tt-Token']) assert.equal(a[name], undefined);
for (const ticket of ['', '-1', 'no', '0', '9007199254740992']) assert.throws(() => signer.headers(url.replace('1794387600123', ticket), body));
assert.throws(() => signer.headers(url.replace('aid=8662', 'aid=no'), body));
assert.equal(signer.gorgon('a=1', 1794387600, 3, 4).length, 44);
const source = fs.readFileSync(path.join(__dirname, '../src/native/app-source.js'), 'utf8');
const policy = source.slice(source.indexOf('    const variantsFrom = async (response) => {'), source.indexOf("    let identity = null, registrationReason = '';"));
assert.equal(crypto.createHash('sha256').update(policy.replace(/^\s*\/\/.*$/gm, '').replace(/\s+/g, ' ').trim()).digest('hex'), 'dbad5e7dfaa1d92c109498718eb0bbf17bf6b3b9c9106e47dd1bf72730b5a882');
console.log('PASS playback request bytes, clock alignment, fresh signatures, malformed inputs, and unchanged stream-selection policy');
